/**
 * 讀取卡住時，代替 SDK 宣告「這條連線死了」。
 *
 * 為什麼需要這種東西：量測顯示手機上進任務列表有 44% 的機率卡 30 秒，而那
 * 30 秒不是在重連，是在「發現自己該重連」—— Firestore 的連線從背景回來之後
 * 已經死了但沒有報錯，SDK 以為一切正常，於是等一個永遠不會來的回應。
 *
 * 判斷「死了」的唯一方法就是等，所以那 30 秒是**偵測成本**，不是重連成本。
 * 這裡把偵測成本從 30 秒壓到 2.5 秒：時間到還沒回來，就當它死了。
 *
 * 純函式模組，不 import firebase 也不 import vue —— 要做什麼補救由呼叫端
 * 傳進來。這樣「多久算卡住」跟「卡住要做什麼」可以分開測。
 */

/**
 * 2.5 秒。
 *
 * 下限是健康時的實測值：同一個查詢在連線正常時是 49～99ms，所以 2.5 秒有
 * 25 倍以上的餘裕，慢一點的網路不會被誤判。上限是使用者的耐心 —— 再往上加
 * 只是讓人多盯著空白畫面，而我們已經知道超過這條線的樣本全都是 30 秒那一群，
 * 沒有任何一筆落在中間。
 */
export const STALL_TIMEOUT_MS = 2500;

/**
 * 監看一個讀取，太久沒回來就呼叫 `onStall`。
 *
 * 注意它**不會**取消或取代原本那個 promise —— 回傳的還是它，成功失敗都原樣
 * 傳出去。補救動作（切斷再重連）本身就會讓卡住的那個讀取從快取回來，所以
 * 這裡不需要自己準備替代品，也就不會有「兩份結果誰贏」的競爭。
 */
export function guardStall<T>(
  read: Promise<T>,
  onStall: () => void,
  timeoutMs = STALL_TIMEOUT_MS
): Promise<T> {
  const timer = setTimeout(onStall, timeoutMs);
  return read.finally(() => clearTimeout(timer));
}
