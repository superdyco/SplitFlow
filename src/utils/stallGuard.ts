/**
 * 讀取卡住時，代替 SDK 宣告「這條連線死了」。
 *
 * 為什麼需要這種東西：量測顯示手機上進任務列表會週期性地卡 30 秒，而那 30 秒
 * 不是在重連，是在「發現自己該重連」—— 連線已經死了但沒有報錯，SDK 以為一切
 * 正常，於是等一個永遠不會來的回應，同時扣著本機那份快取不發。
 *
 * 判斷「死了」的唯一方法就是等，所以那 30 秒是**偵測成本**，不是重連成本。
 * 這裡把偵測成本壓到 1.5 秒：時間到還沒回來，就當它死了。
 *
 * 什麼情況會讓連線死掉，到現在還不知道。**不是**從背景回來 —— 那是我們一開始
 * 的假設，量了之後推翻了：卡住的兩筆整段都在前景，而背景 52 秒回來的那兩筆
 * 只花 72ms。目前只知道它成群出現，死一小段時間之後自己恢復。
 *
 * 好消息是這個機制不需要知道原因也能用。
 *
 * 純函式模組，不 import firebase 也不 import vue —— 要做什麼補救由呼叫端
 * 傳進來。這樣「多久算卡住」跟「卡住要做什麼」可以分開測。
 */

/**
 * 1.5 秒。
 *
 * 一開始設 2.5 秒，實測驗證過之後往下調：21 筆健康樣本裡最慢的是 133ms
 * （而且那還是含 chunk 下載的冷啟動），一次誤觸發都沒有。而卡住的樣本全部
 * 落在 30 秒那一群，中間完全沒有東西 —— 這條線畫在哪都不會誤判，所以往下畫。
 *
 * **但這是在家裡的網路上量的。** 這是出國用的 App，真正的 3G 漫遊下一趟合法的
 * 查詢可能就超過 1.5 秒，那時會誤觸發。後果不算災難（顯示快取 + 重建連線），
 * 但在爛網路上重建連線本身有成本。等有國外的樣本再回頭調這個數字。
 */
export const STALL_TIMEOUT_MS = 1500;

/**
 * 監看一個讀取，太久沒回來就呼叫 `onStall`。
 *
 * 注意它**不會**取消或取代原本那個 promise —— 回傳的還是它，成功失敗都原樣
 * 傳出去。補救動作（切斷再重連）本身就會讓卡住的那個讀取從快取回來，所以
 * 這裡不需要自己準備替代品，也就不會有「兩份結果誰贏」的競爭。
 */
export function guardStall<T>(
  read: Promise<T>,
  onStall: () => void,
  timeoutMs = STALL_TIMEOUT_MS
): Promise<T> {
  const timer = setTimeout(onStall, timeoutMs);
  return read.finally(() => clearTimeout(timer));
}
